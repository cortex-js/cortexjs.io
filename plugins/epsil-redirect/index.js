// Redirect the former mathlive.io homes of documentation that moved to
// epsil.dev: the Epsil language docs (first at /cortex/, then at /epsil/), and
// the Compute Engine and MathJSON docs (/compute-engine/, /math-json/, the
// same paths on epsil.dev). The docs plugin no longer builds them here
// (`docs.exclude` in docusaurus.config.ts), so those routes would 404.
//
// mathlive.io is served by GitHub Pages, which cannot issue a real 301, so
// each old URL gets a stub page: a canonical link (so search engines transfer
// the URL), a meta refresh (so a browser with JS disabled still moves), and a
// location.replace (so the entry is not left in the back-button history).
// The script keeps the fragment of the URL, so an old link to an anchor
// (`/compute-engine/reference/arithmetic/#Add`) reaches the same anchor on the
// new site, where a moved page redirects it to its entry. The meta refresh
// cannot keep it.
//
// The Epsil route table is generated by `scripts/sync-epsil-docs.mjs`, which
// is the only place that sees each page's URL both before and after the move.
// The Compute Engine table, `config/ce-redirects.json`, lists the pages that
// mathlive.io published; their paths did not change.

import fs from "node:fs/promises";
import path from "node:path";

function stubHtml(target, siteTitle, what) {
  const escaped = target.replace(/&/g, "&amp;").replace(/"/g, "&quot;");
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Redirecting to ${escaped}</title>
<link rel="canonical" href="${escaped}">
<meta name="robots" content="noindex">
<meta http-equiv="refresh" content="0; url=${escaped}">
<script>window.location.replace("${escaped}" + window.location.hash);</script>
</head>
<body>
<p>The ${what} has moved to <a href="${escaped}">${escaped}</a>.</p>
<p><a href="/">Back to ${siteTitle}</a></p>
</body>
</html>
`;
}

/**
 * @param {import('@docusaurus/types').LoadContext} context
 * @param {{redirects: {target: string, routes: Record<string, string>}, alsoUnder?: string[], what?: string}} options
 */
export default function epsilRedirectPlugin(context, options = {}) {
  const { siteConfig } = context;
  const { redirects, alsoUnder = [], what = "Epsil documentation" } = options;

  return {
    name: "epsil-redirect",

    async postBuild({ outDir }) {
      if (!redirects?.routes) {
        console.warn("[epsil-redirect] No route table supplied; nothing emitted");
        return;
      }

      const { target, routes } = redirects;
      let count = 0;

      for (const [from, to] of Object.entries(routes)) {
        const destination = new URL(to, target).href;

        // The canonical old path, plus any earlier alias of the same section
        // (/cortex/… before the rename). Writing those here rather than
        // leaving them to plugin-client-redirects avoids a double hop:
        // /cortex/syntax/ -> /epsil/syntax/ -> epsil.dev/syntax/.
        const paths = [from, ...alsoUnder.map((prefix) => from.replace(/^\/epsil/, prefix))];

        for (const p of new Set(paths)) {
          const file = path.join(outDir, p, "index.html");
          await fs.mkdir(path.dirname(file), { recursive: true });
          await fs.writeFile(file, stubHtml(destination, siteConfig.title, what), "utf8");
          count++;
        }
      }

      console.log(`[epsil-redirect] ${count} redirect stubs for the ${what} -> ${target}`);
    },
  };
}
